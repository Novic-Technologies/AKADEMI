interface I18nContextValue {
  lang: LangCode;
  setLang: (code: LangCode) => void;
  dir: 'ltr' | 'rtl';
  t: I18nMessages;
}

const STORAGE_KEY = 'akademi_lang';

const I18nContext = createContext<I18nContextValue>({
  lang: 'en',
  setLang: () => {},
  dir: 'ltr',
  t: EN,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<LangCode>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as LangCode | null;
      if (saved && LANGUAGES.some((l) => l.code === saved)) {
        return saved;
      }
    } catch {
      // ignore storage failure
    }
    return 'en';
  });

  const meta = LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0];
  const dir = meta.dir;

  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // ignore
    }
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const setLang = (code: LangCode) => {
    setLangState(code);
  };

  const t: I18nMessages =
    lang === 'en' ? EN : { ...EN, ...(OVERRIDES[lang] || {}) };

  return (
    <I18nContext.Provider value={{ lang, setLang, dir, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export function useI18n() {
  return useContext(I18nContext);
}

interface LanguageSelectorProps {
  compact?: boolean;
  className?: string;
}

export const LanguageSelector: React.FC<LanguageSelectorProps> = ({
  compact = false,
  className = '',
}) => {
  const { lang, setLang } = useI18n();
  return (
    <label
      className={`inline-flex min-h-[40px] items-center gap-1.5 rounded-lg border border-[#C8BFA8] bg-[#EFECE3] px-2.5 py-1.5 text-sm text-[#0C1B2E] ${className}`}
    >
      <Globe className="h-4 w-4 shrink-0 text-[#A44A1C]" />
      <select
        aria-label="Language"
        value={lang}
        onChange={(e) => setLang(e.target.value as LangCode)}
        className={`bg-transparent text-sm font-semibold text-[#0C1B2E] focus:outline-none ${
          compact ? 'max-w-[110px]' : ''
        }`}
      >
        {LANGUAGES.map((l) => (
          <option key={l.code} value={l.code}>
            {l.label}
          </option>
        ))}
      </select>
    </label>
  );
};
